// Volume control
document.addEventListener('DOMContentLoaded', () => {
  const volumeSlider = document.getElementById('radioVolume');
  const audio = document.getElementById('radioAudio');
  
  if (volumeSlider && audio) {
    // Sincronizar volume inicial
    audio.volume = volumeSlider.value / 100;
    
    const updateVol = (e) => {
      const vol = e.target.value / 100;
      audio.volume = vol;
      audio.muted = (vol === 0);
      updateVolumeIcon(vol);
    };

    volumeSlider.addEventListener('input', updateVol);
    volumeSlider.addEventListener('change', updateVol);
  }

  window.toggleMute = function() {
    if (!audio) return;
    audio.muted = !audio.muted;
    const volIcon = document.getElementById('volIcon');
    if (audio.muted) {
      volIcon.setAttribute('data-lucide', 'volume-x');
      volumeSlider.style.opacity = '0.3';
    } else {
      updateVolumeIcon(audio.volume);
      volumeSlider.style.opacity = '1';
    }
    if (window.lucide) window.lucide.createIcons();
  };

  function updateVolumeIcon(vol) {
    const volIcon = document.getElementById('volIcon');
    if (!volIcon) return;
    
    let iconName = 'volume-2';
    if (vol === 0) iconName = 'volume-x';
    else if (vol < 0.5) iconName = 'volume-1';
    
    volIcon.setAttribute('data-lucide', iconName);
    if (window.lucide) window.lucide.createIcons();
  }

  // Audio event listeners para estados
  if (audio) {
    audio.addEventListener('waiting', () => {
      if (radioIsPlaying) {
        const label = document.getElementById('statusLabel');
        const dot = document.querySelector('.status-dot');
        if (label) { label.textContent = 'Carregando...'; label.style.color = 'var(--accent)'; }
        if (dot) dot.className = 'status-dot loading';
      }
    });

    audio.addEventListener('playing', () => {
      const label = document.getElementById('statusLabel');
      const dot = document.querySelector('.status-dot');
      if (label) { label.textContent = 'Ao Vivo'; label.style.color = '#22c55e'; }
      if (dot) dot.className = 'status-dot playing';
    });

    audio.addEventListener('error', () => {
      if (radioIsPlaying && radioRetryCount < RADIO_MAX_RETRIES) {
        radioRetryCount++;
        const label = document.getElementById('statusLabel');
        if (label) { label.textContent = 'Reconectando...'; label.style.color = 'var(--accent)'; }
        setTimeout(() => {
          audio.load();
          audio.play().catch(() => {});
        }, 3000);
      }
    });

    audio.addEventListener('stalled', () => {
      if (radioIsPlaying) {
        const label = document.getElementById('statusLabel');
        if (label) { label.textContent = 'Buffering...'; label.style.color = 'var(--accent)'; }
      }
    });
  }

  // ── Carrossel da Diretoria ──
  const strip = document.getElementById('diretoria-strip');
  const btnPrev = document.getElementById('diretoria-prev');
  const btnNext = document.getElementById('diretoria-next');

  if (strip && btnPrev && btnNext) {
    const scrollAmount = 300;
    
    btnPrev.addEventListener('click', () => {
      strip.scrollBy({ left: -scrollAmount, behavior: 'smooth' });
    });

    btnNext.addEventListener('click', () => {
      strip.scrollBy({ left: scrollAmount, behavior: 'smooth' });
    });

    // Ocultar setas se não houver scroll
    const toggleArrows = () => {
      btnPrev.style.display = strip.scrollLeft > 0 ? 'flex' : 'none';
      btnNext.style.display = (strip.scrollLeft + strip.clientWidth < strip.scrollWidth - 10) ? 'flex' : 'none';
    };

    strip.addEventListener('scroll', toggleArrows);
    window.addEventListener('resize', toggleArrows);
    setTimeout(toggleArrows, 500); // Check inicial
  }

  renderCongs();
  observeReveal();
  if (window.lucide) {
    window.lucide.createIcons();
  }
});

